"""NixOS backend: generate a flake configuration from the profile, then nixos-install."""

from __future__ import annotations

import json

from ..util import run, write_file
from . import ASSETS, DEFAULT_PASSWORDS, KERNEL_CONSOLE, PASSWORD_FLAG, Context


def channel_url(version: str) -> str:
    # The channel tarball is exactly what cache.nixos.org has prebuilt, and it
    # does not use the GitHub API (no rate limit). Resolved at install time → newest.
    return f"https://channels.nixos.org/nixos-{version}/nixexprs.tar.xz"


def nix_str(value: str) -> str:
    """Nix string literal (JSON escaping is valid Nix for plain strings)."""
    return json.dumps(value).replace("${", "\\${")


def render(profile, plan, lang: dict, hostname: str, version: str) -> dict[str, str]:
    """Return the files for /etc/nixos (relative name → content)."""
    files: dict[str, str] = {}

    item_modules = []
    packages = list(plan.packages)
    for item_id, sec in plan.items:
        body = (sec.get("config") or "").strip()
        packages += sec.get("packages", []) or []
        if body:
            indented = "\n".join("      " + line if line.strip() else "" for line in body.splitlines())
            item_modules.append(f"    # {item_id}\n    ({{ config, pkgs, lib, ... }}: {{\n{indented}\n    }})")
    files["easylinux-items.nix"] = (
        "# Generated by EasyLinux from the catalog. One module per item.\n"
        "{\n  imports = [\n" + "\n".join(item_modules) + "\n  ];\n}\n"
    )

    users = []
    for u in profile.users:
        groups = ['"networkmanager"', '"video"', '"audio"'] + (['"wheel"'] if u.admin else [])
        users.append(
            f"  users.users.{nix_str(u.name)} = {{\n"
            f"    isNormalUser = true;\n"
            f"    extraGroups = [ {' '.join(groups)} ];\n"
            f"    initialPassword = {nix_str(u.password)};\n"
            f"  }};"
        )
    pkg_list = " ".join(f"pkgs.{nix_str(p)}" for p in dict.fromkeys(packages))
    first_login = ""
    if profile.desktop:
        first_login = """
  # First login: force a new password (see first-login.sh)
  imports = [ ./easylinux-first-login.nix ];"""
        files["easylinux-first-login.nix"] = FIRST_LOGIN_NIX
        files["first-login.sh"] = (ASSETS / "first-login.sh").read_text(encoding="utf-8")
        files["set-password.sh"] = (ASSETS / "set-password.sh").read_text(encoding="utf-8")

    files["configuration.nix"] = f"""# Generated by EasyLinux for profile '{profile.id}'.
{{ config, pkgs, lib, ... }}:
{{{first_login}
  boot.loader.systemd-boot.enable = true;
  boot.loader.efi.canTouchEfiVariables = true;
  boot.kernelParams = [ {' '.join(nix_str(p) for p in KERNEL_CONSOLE)} ];

  networking.hostName = {nix_str(hostname)};
  networking.networkmanager.enable = true;

  time.timeZone = {nix_str(profile.timezone)};
  i18n.defaultLocale = {nix_str(lang["locale"])};
  console.keyMap = {nix_str(lang["console"])};
  services.xserver.xkb.layout = {nix_str(lang["keyboard"])};

  nixpkgs.config.allowUnfree = {str(plan.unfree).lower()};
  nix.settings.experimental-features = [ "nix-command" "flakes" ];

{chr(10).join(users)}

  environment.systemPackages = [ {pkg_list} ];

  system.stateVersion = {nix_str(version)};
}}
"""
    files["flake.nix"] = f"""# Generated by EasyLinux. Update the system with:
#   sudo nix flake update --flake /etc/nixos && sudo nixos-rebuild switch
{{
  inputs.nixpkgs.url = {nix_str(channel_url(version))};
  outputs = {{ nixpkgs, ... }}: {{
    nixosConfigurations.{nix_str(hostname)} = nixpkgs.lib.nixosSystem {{
      modules = [ ./configuration.nix ./hardware-configuration.nix ./easylinux-items.nix ];
    }};
  }};
}}
"""
    return files


FIRST_LOGIN_NIX = r"""{ pkgs, ... }:
let
  setPassword = pkgs.writeShellApplication {
    name = "easylinux-set-password";
    runtimeInputs = [ pkgs.shadow pkgs.gnugrep pkgs.coreutils ];
    text = builtins.readFile ./set-password.sh;
    checkPhase = "";
  };
  firstLogin = pkgs.writeShellApplication {
    name = "easylinux-first-login";
    runtimeInputs = [ pkgs.zenity pkgs.gnugrep pkgs.coreutils pkgs.util-linux ];
    text = ''
      export EASYLINUX_SETPW=${setPassword}/bin/easylinux-set-password
      export PATH="/run/wrappers/bin:$PATH"
    '' + builtins.readFile ./first-login.sh;
    checkPhase = "";
  };
in
{
  environment.systemPackages = [ firstLogin ];
  security.sudo.extraRules = [{
    users = [ "ALL" ];
    commands = [{ command = "${setPassword}/bin/easylinux-set-password"; options = [ "NOPASSWD" ]; }];
  }];
  # X11 sessions (e.g. awesome) don't run XDG autostart → start it from the session script
  services.xserver.displayManager.sessionCommands = "${firstLogin}/bin/easylinux-first-login &";
  # Wayland/XDG-autostart desktops
  environment.etc."xdg/autostart/easylinux-first-login.desktop".text = ''
    [Desktop Entry]
    Type=Application
    Name=EasyLinux first login
    Exec=${firstLogin}/bin/easylinux-first-login
    NoDisplay=true
  '';
}
"""


def install(ctx: Context) -> None:
    log, mnt = ctx.log, ctx.mnt
    ctx.progress(16, "step_configure")
    boot = mnt / "boot"
    boot.mkdir(parents=True, exist_ok=True)
    run(["mount", "-o", "umask=0077", ctx.esp, str(boot)], log)
    run(["nixos-generate-config", "--root", str(mnt)], log)

    etc = mnt / "etc/nixos"
    (etc / "configuration.nix").unlink(missing_ok=True)
    for name, content in render(ctx.profile, ctx.plan, ctx.lang, ctx.hostname, ctx.releases["nixos"]).items():
        write_file(etc / name, content)

    if ctx.has_desktop:
        names = "".join(f"{u.name}\n" for u in ctx.profile.users)
        write_file(mnt / PASSWORD_FLAG.lstrip("/"), names, 0o644)
        write_file(mnt / DEFAULT_PASSWORDS.lstrip("/"),
                   "".join(f"{u.name}:{u.password}\n" for u in ctx.profile.users), 0o600)

    ctx.progress(25, "step_software")
    run(["nixos-install", "--root", str(mnt), "--no-root-passwd",
         "--flake", f"{etc}#{ctx.hostname}",
         "--option", "experimental-features", "nix-command flakes"], log)

    if not ctx.has_desktop:
        ctx.progress(92, "step_users")
        for u in ctx.profile.users:
            run(["nixos-enter", "--root", str(mnt), "-c", f"chage -d 0 {u.name}"], log)
